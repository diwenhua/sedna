export function createTranslator(locale: UiLocale) {
  const dictionary = dictionaries[locale];
  return (key: TranslationKey) => dictionary[key];
}

export function assistantReplyLocaleLabel(locale: AssistantReplyLocale, t: (key: TranslationKey) => string): string {
  if (locale === "follow_ui") {
    return t("followInterfaceLanguage");
  }
  return locale === "zh-CN" ? t("simplifiedChinese") : t("english");
}
